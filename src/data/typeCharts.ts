function buildChart(types: readonly PokemonType[], rows: readonly (readonly number[])[]): TypeChart {
  return Object.fromEntries(types.map((attackingType, rowIndex) => [
    attackingType,
    Object.fromEntries(types.map((defendingType, columnIndex) => [
      defendingType,
      rows[rowIndex][columnIndex],
    ])),
  ])) as TypeChart
}

